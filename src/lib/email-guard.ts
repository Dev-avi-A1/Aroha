const DISPOSABLE_PATTERN =
  /(^|\.)(temp-?mail|10min(ute)?mail|guerrillamail|mailinator|yopmail|throwaway|trash-?mail|burnermail|dispostable|fakemail|fakeinbox|getnada|tmpmail|mohmal|dropmail)(\.|$)/i;

const BASIC_EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

export function normalizeEmail(raw: string): string {
  return raw.trim().toLowerCase();
}

export function extractEmailDomain(email: string): string {
  const clean = normalizeEmail(email);
  const atIndex = clean.lastIndexOf('@');
  if (atIndex === -1) return '';
  return clean.slice(atIndex + 1);
}

export function isDisposableEmail(email: string): boolean {
  const domain = extractEmailDomain(email);
  if (!domain) return false;
  if (TRUSTED_MAIL_PROVIDERS.has(domain)) return false;

  if (DISPOSABLE_EMAIL_DOMAINS.has(domain)) return true;

  // Match subdomains of known disposable providers (e.g. sub.yopmail.com)
  const parts = domain.split('.');
  for (let i = 1; i < parts.length - 1; i += 1) {
    const parent = parts.slice(i).join('.');
    if (DISPOSABLE_EMAIL_DOMAINS.has(parent)) return true;
  }

  return DISPOSABLE_PATTERN.test(domain);
}

export interface EmailValidationResult {
  valid: boolean;
  disposable: boolean;
  trustedProvider: boolean;
  domain: string;
  reason?: string;
}

export function validateEmailAddress(email: string): EmailValidationResult {
  const clean = normalizeEmail(email);
  const domain = extractEmailDomain(clean);

  if (!BASIC_EMAIL_REGEX.test(clean) || clean.length > 254 || domain.includes('..')) {
    return {
      valid: false,
      disposable: false,
      trustedProvider: false,
      domain,
      reason: 'Enter a valid email address.',
    };
  }

  if (isDisposableEmail(clean)) {
    return {
      valid: false,
      disposable: true,
      trustedProvider: false,
      domain,
      reason: `Temporary or disposable email addresses (@${domain}) are not permitted. Use a permanent mail account.`,
    };
  }

  return {
    valid: true,
    disposable: false,
    trustedProvider: TRUSTED_MAIL_PROVIDERS.has(domain),
    domain,
  };
}
